export function getGame(gameId: string): GameInfo | undefined {
  return games.find((g) => g.id === gameId);
}

export function getOffersForGame(gameId: string): readonly GameOffer[] {
  return precomputedOffers[gameId as GameKey] || Object.freeze([]);
}

export function formatIdr(priceIdr: number): string {
  return `Rp ${priceIdr.toLocaleString('id-ID')}`;
}
